-- PostgreSQL 18, yangi demo baza. Tegishli CREATE SCHEMA huquqi kerak.
CREATE SCHEMA library;
CREATE TABLE library.categories(id BIGINT PRIMARY KEY,name TEXT NOT NULL UNIQUE);
CREATE TABLE library.books(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title TEXT NOT NULL CHECK(length(trim(title))>0),
 category_id BIGINT NOT NULL REFERENCES library.categories(id) ON DELETE RESTRICT,
 price_sum BIGINT NOT NULL CHECK(price_sum>=0),stock INTEGER NOT NULL DEFAULT 0 CHECK(stock>=0)
);
CREATE TABLE library.members(id BIGINT PRIMARY KEY,name TEXT NOT NULL,card_no TEXT NOT NULL UNIQUE,group_name TEXT NOT NULL);
CREATE TABLE library.loans(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES library.members(id) ON DELETE RESTRICT,
 book_id BIGINT NOT NULL REFERENCES library.books(id) ON DELETE RESTRICT,
 issued_on DATE NOT NULL,due_on DATE NOT NULL,returned_on DATE,
 CHECK(due_on>=issued_on),CHECK(returned_on IS NULL OR returned_on>=issued_on)
);
